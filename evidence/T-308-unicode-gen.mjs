// T-308 (TERM-104): builds src/shell/unicodeWidthData.ts from the public Unicode Character Database.
// Inputs (Unicode 16.0.0, https://www.unicode.org/Public/16.0.0/ucd/):
//   EastAsianWidth.txt, emoji/emoji-data.txt, extracted/DerivedGeneralCategory.txt
// Usage: node evidence/T-308-unicode-gen.mjs <folder with the three files> > src/shell/unicodeWidthData.ts
import { readFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node T-308-unicode-gen.mjs <ucd folder>");
const read = (f) => readFileSync(join(dir, f), "utf8");

/** Every "a..b ; value" (or "a ; value") line, plus "# @missing:" defaults when asked. */
function rows(text, missing = false) {
  const out = [];
  for (const raw of text.split(/\r?\n/)) {
    let line = raw;
    if (missing && line.startsWith("# @missing:")) line = line.slice("# @missing:".length);
    else line = line.replace(/#.*/, "");
    const m = /^\s*([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*([A-Za-z_]+)/.exec(line);
    if (!m) continue;
    out.push({ a: parseInt(m[1], 16), b: parseInt(m[2] ?? m[1], 16), v: m[3], missing: raw.startsWith("# @missing:") });
  }
  return out;
}

const MAX = 0x10ffff;
const eaw = new Uint8Array(MAX + 1); // 0 = narrow-ish, 2 = wide
// Defaults first (the file's @missing lines), then the explicit lines over them.
const eawRows = rows(read("EastAsianWidth.txt"), true);
for (const r of eawRows.filter((r) => r.missing)) for (let c = r.a; c <= r.b; c++) eaw[c] = r.v === "W" || r.v === "F" ? 2 : 0;
for (const r of eawRows.filter((r) => !r.missing)) for (let c = r.a; c <= r.b; c++) eaw[c] = r.v === "W" || r.v === "F" ? 2 : 0;

const emoji = rows(read("emoji-data.txt"));
for (const r of emoji.filter((r) => r.v === "Emoji_Presentation")) for (let c = r.a; c <= r.b; c++) eaw[c] = 2;

const zero = new Uint8Array(MAX + 1);
for (const r of rows(read("DerivedGeneralCategory.txt"))) {
  if (r.v === "Mn" || r.v === "Me" || r.v === "Cf") for (let c = r.a; c <= r.b; c++) zero[c] = 1;
}
// Format characters that are drawn (soft hyphen, prepended concatenation marks) keep one cell.
for (const c of [0x00ad, 0x0600, 0x0601, 0x0602, 0x0603, 0x0604, 0x0605, 0x06dd, 0x070f, 0x0890, 0x0891, 0x08e2, 0x110bd, 0x110cd]) zero[c] = 0;
// Hangul Jamo medial vowels and final consonants join the leading consonant's two cells.
for (let c = 0x1160; c <= 0x11ff; c++) zero[c] = 1;
for (let c = 0xd7b0; c <= 0xd7ff; c++) zero[c] = 1;

const pict = new Uint8Array(MAX + 1);
for (const r of emoji.filter((r) => r.v === "Extended_Pictographic")) for (let c = r.a; c <= r.b; c++) pict[c] = 1;

/** Flat [start, end, start, end, ...] list of the runs where the test holds. */
function ranges(test) {
  const out = [];
  let start = -1;
  for (let c = 0; c <= MAX + 1; c++) {
    const on = c <= MAX && test(c);
    if (on && start < 0) start = c;
    if (!on && start >= 0) {
      out.push(start, c - 1);
      start = -1;
    }
  }
  return out;
}

const hex = (n) => "0x" + n.toString(16);
const list = (xs) => {
  const parts = xs.map(hex);
  const lines = [];
  for (let i = 0; i < parts.length; i += 12) lines.push("  " + parts.slice(i, i + 12).join(", ") + ",");
  return lines.join("\n");
};

const ZERO = ranges((c) => zero[c] === 1);
const WIDE = ranges((c) => zero[c] === 0 && eaw[c] === 2);
const PICT = ranges((c) => pict[c] === 1);

process.stdout.write(`// GENERATED by evidence/T-308-unicode-gen.mjs from the Unicode Character Database 16.0.0
// (https://www.unicode.org/Public/16.0.0/ucd/: EastAsianWidth.txt, emoji/emoji-data.txt,
// extracted/DerivedGeneralCategory.txt; Unicode License v3). Do not edit by hand: rerun the script.
// Each list is flat [first, last, first, last, ...] code point runs, sorted.

export const UNICODE_VERSION = "16.0.0";

/** Zero cells: nonspacing and enclosing marks, format characters (bar the drawn ones), Hangul Jamo vowels and finals. */
export const ZERO_WIDTH: readonly number[] = [
${list(ZERO)}
];

/** Two cells: East Asian Width W or F, plus every Emoji_Presentation character. */
export const DOUBLE_WIDTH: readonly number[] = [
${list(WIDE)}
];

/** Extended_Pictographic: the characters an emoji sequence (ZWJ, VS16, skin tone) builds on. */
export const PICTOGRAPHIC: readonly number[] = [
${list(PICT)}
];
`);
